<p>众人搬家坚持明码标价、标准作业、费用提前确认。居民搬家公开大型面包车380元、小型厢式货车469元、大型厢式货车569元三种套餐，均包含装车、运输、卸车；日式精品搬家每立方米320元、10立方米起，半日式搬家每立方米280元、5立方米起。套餐包含里程、超里程计费、无电梯楼层费及其他费用构成，可在<a href="/pricing.html">报价说明</a>页面查询。</p>
<p>高层吊装和工厂搬迁采用免费上门勘测、勘测后分项报价的方式，方案明确吊装设备、操作人员、设备拆装、包装及运输等项目。半日式、精品日式、高层吊装、工厂及大件居民搬家均提供免费上门勘测，勘测后不下单仍然免费。</p>
<p>公司实行合同锁价：作业前书面确认服务项目与全部费用，约定范围内不临时加价；公司勘测漏项不向客户加价；客户新增服务，先确认费用再实施。从前期沟通、现场防护、装卸运输到交接验收，明确各环节要求。</p>
