    <div class="qualification-heading">
        <span>04 / 安全作业制度</span>
        <h2 id="safety-policy-title">众人搬家安全作业制度</h2>
        <p>搬家公司内部安全作业制度</p>
    </div>
    <details class="safety-policy-chapter" open>
        <summary><h3>第一章 总则</h3></summary>
        <div class="safety-policy-body">
            <h4>第一条 制定目的</h4>
            <p>为规范公司搬家作业全流程操作，防范人身伤害、物品损毁、交通事故、客户纠纷等安全事故发生，保障作业人员人身安全、客户财产安全及公司财产与声誉，建立标准化、规范化、常态化的安全作业管理体系，结合公司搬家服务实际运营情况，特制定本制度。</p>
            <h4>第二条 适用范围</h4>
            <p>本制度适用于公司所有搬家作业人员、驾驶员、现场班组长、调度人员及参与搬家作业的所有内部员工，覆盖上门勘测、装车、运输、卸车、搬运、摆放、收尾清场等全部作业环节，所有岗位人员必须严格遵照执行。</p>
            <h4>第三条 核心原则</h4>
            <p>坚持“安全第一、预防为主、规范操作、全程可控、责任到人”的核心原则，所有作业以安全为前提，杜绝违规操作、侥幸作业，做到事前防范、事中管控、事后复盘，全面规避各类安全风险。</p>
            <h4>第四条 管理职责</h4>
            <ol>
                <li>公司管理层：为安全作业第一责任主体，负责制度制定、修订、落地监督，统筹安全培训、隐患排查、事故处理等工作。</li>
                <li>安全管理员：负责日常安全巡查、员工安全培训、作业隐患整改跟踪、安全档案记录、事故上报与复盘工作。</li>
                <li>现场班组长：为单次搬家作业现场安全第一责任人，负责作业前交底、作业中全程监督、作业后安全核查，及时制止违规操作。</li>
                <li>全体作业人员：严格遵守本制度各项规定，规范岗位操作，主动排查岗位安全隐患，对自身作业安全直接负责。</li>
            </ol>
        </div>
    </details>
    <details class="safety-policy-chapter">
        <summary><h3>第二章 人员安全管理规范</h3></summary>
        <div class="safety-policy-body">
            <h4>第一条 上岗资质要求</h4>
            <ol>
                <li>所有作业人员必须年满18周岁，身体健康，无高血压、心脏病、眩晕症、肢体残疾等不适合重体力搬运及高空作业的疾病，入职前需完成体检，留存体检报告。</li>
                <li>驾驶员必须持有对应准驾车型有效驾驶证，驾龄满3年及以上，无重大交通事故记录，定期参加交通安全培训，持证上岗。</li>
                <li>新员工必须完成岗前安全培训、实操演练，考核合格后方可独立上岗；老员工每月参与常态化安全复训，未参训、考核不合格者禁止上岗作业。</li>
            </ol>
            <h4>第二条 作业仪容与防护要求</h4>
            <ol>
                <li>作业期间必须统一穿着公司工装、防滑劳保鞋，高空作业、大件搬运需佩戴防滑手套、护腰、安全帽等防护用品，严禁赤脚、穿拖鞋、凉鞋作业。</li>
                <li>作业人员不得佩戴尖锐饰品、长头发需盘起固定，避免作业中勾挂物品、引发安全事故。</li>
                <li>严禁酒后上岗、疲劳上岗、带病上岗，作业期间禁止吸烟、酗酒、嬉戏打闹、擅自离岗。</li>
            </ol>
            <h4>第三条 人员作业行为规范</h4>
            <ol>
                <li>搬运作业遵循“量力而行、多人配合、稳拿轻放”原则，禁止单人强行搬运超重、超大、超高物品，大件家具、家电必须2人及以上协同作业。</li>
                <li>上下楼梯、进出电梯时稳步慢行，严禁奔跑、跳跃，禁止在楼道、电梯内打闹，避免磕碰墙体、客户物品及自身摔伤。</li>
                <li>严禁私自攀爬窗台、阳台、外墙进行搬运作业，特殊高空搬运场景必须报备管理层，做好防护措施后方可作业。</li>
                <li>作业中严格遵守客户现场规定，不随意触碰客户私人物品、电器设备、燃气阀门等危险设施，杜绝违规操作引发安全隐患。</li>
            </ol>
        </div>
    </details>
    <details class="safety-policy-chapter">
        <summary><h3>第三章 设备与工具安全管理</h3></summary>
        <div class="safety-policy-body">
            <h4>第一条 作业设备检查维护</h4>
            <ol>
                <li>公司所有搬运设备（叉车、手动液压车、吊装带、搬运滑轮、伸缩梯、承重垫板等）、防护工具、捆绑耗材必须建立台账，专人管理、定期检修。</li>
                <li>每次作业前，班组长必须对所有工具设备进行全面检查，重点排查吊装带有无破损、断裂，梯子有无松动、打滑，推车车轮、轴承是否完好，捆绑绳是否牢固，存在安全隐患的设备立即停用、报修，严禁带病作业。</li>
                <li>设备使用严格遵循操作规程，禁止超负荷、超范围使用，吊装设备严禁超重吊装，梯子严禁超高、超载使用。</li>
            </ol>
            <h4>第二条 运输车辆安全管理</h4>
            <ol>
                <li>搬家运输车辆必须定期年检、保养，每日出车前驾驶员需检查刹车、轮胎、灯光、水箱、油路、车厢固定装置等，确认无故障后方可出车。</li>
                <li>车厢防护设施齐全，防滑垫、固定绑带、防撞护角、防雨布等耗材常备齐全，车辆内饰、车厢定期清洁，杜绝杂物、油污影响作业安全。</li>
                <li>车辆出现故障必须立即停运检修，严禁故障车辆、逾期未检车辆上路作业。</li>
            </ol>
            <h4>第三条 工具存放与保管</h4>
            <ol>
                <li>作业工具、设备用完后及时清洁、归位存放，分类摆放整齐，避免杂乱堆放引发磕碰、坠落风险。</li>
                <li>精密、专用搬运工具专人保管，定期保养维护，损坏、报废设备及时登记更换，严禁私自丢弃、挪用公司作业设备。</li>
            </ol>
        </div>
    </details>
    <details class="safety-policy-chapter">
        <summary><h3>第四章 现场搬运作业安全规范</h3></summary>
        <div class="safety-policy-body">
            <h4>第一条 作业前安全准备</h4>
            <ol>
                <li>接单后调度人员提前对接客户，确认搬运物品类型、重量、尺寸，明确作业场地（楼道、电梯、楼层）环境，提前排查狭窄通道、陡坡、无护栏楼梯、老旧地面等风险场景。</li>
                <li>作业团队上门后，班组长首先对作业现场进行安全勘测，清理作业通道杂物、障碍物，对墙面、地面、电梯、门框做好防护铺垫，避免作业磕碰损坏。</li>
                <li>提前与客户确认贵重物品、易碎品、危险品、精密仪器等特殊物品，单独登记、单独打包、单独搬运，明确搬运注意事项，杜绝盲目作业。</li>
                <li>作业前召开简短安全交底会，明确分工、作业流程、风险点位及应急事项，确保全员清晰作业要求。</li>
            </ol>
            <h4>第二条 物品打包安全规范</h4>
            <ol>
                <li>易碎品（玻璃制品、陶瓷、灯具、家电屏幕等）必须使用气泡膜、泡沫、纸箱分层包裹，做好防震、防磕碰处理，外包装标注“易碎、轻放、朝上”标识。</li>
                <li>家具类物品拆卸前先断电、断水、清空内部物品，尖锐边角加装护角，木质、皮质家具做好防尘、防刮花防护，拆卸配件分类密封收纳，防止丢失、掉落。</li>
                <li>电器类（冰箱、洗衣机、空调、电视等）提前断电静置，排空积水，线路收纳固定，严禁拖拽电线搬运设备。</li>
                <li>严禁打包、搬运易燃易爆（汽油、酒精、鞭炮）、腐蚀性、剧毒、高压气瓶等违禁危险品，发现客户物品含违禁品，立即告知客户并拒绝搬运，做好登记说明。</li>
            </ol>
            <h4>第三条 装卸搬运安全规范</h4>
            <ol>
                <li>装车遵循“重下轻上、大下小上、稳固对称、分类摆放”原则，重物、大件家具放置车厢底部居中，易碎品、轻物放置上层，物品之间用绑带固定、缓冲物填充，防止运输中晃动、碰撞、坠落。</li>
                <li>卸车作业先轻后重、先上后下，稳步有序操作，禁止随意抛掷、推拉、拖拽物品，杜绝野蛮作业。</li>
                <li>楼道、电梯搬运严格控制物品倾斜角度，避免物品磕碰墙体、电梯门、消防设施，狭窄通道专人指挥疏导，防止人员、物品拥挤碰撞。</li>
                <li>超重物品搬运全程统一口令、同步发力，平稳起落、稳步移动，禁止突发发力、急停急转，避免扭伤、砸伤事故。</li>
                <li>雨天、雪天户外作业需做好防滑、防雨措施，地面积水、积雪及时清理，物品做好防水包裹，杜绝打滑摔伤、物品受潮损坏。</li>
            </ol>
            <h4>第四条 作业收尾安全规范</h4>
            <ol>
                <li>物品全部搬运到位后，按照客户要求平稳摆放、对位，调整平整稳固，避免家具、家电倾斜倾倒。</li>
                <li>全面检查作业现场、车厢、楼道，清理作业垃圾、废弃包装、工具杂物，杜绝遗留安全隐患。</li>
                <li>与客户核对物品数量、完好情况，确认无遗漏、无损坏，完成交接签字，作业人员方可离场。</li>
            </ol>
        </div>
    </details>
    <details class="safety-policy-chapter">
        <summary><h3>第五章 交通运输安全规范</h3></summary>
        <div class="safety-policy-body">
            <h4>第一条 行车安全要求</h4>
            <ol>
                <li>驾驶员必须严格遵守交通法规，杜绝超速、闯红灯、疲劳驾驶、酒后驾驶、违规变道、强行超车等违法行为。</li>
                <li>运输途中匀速行驶，途经颠簸路段、陡坡、弯道减速慢行，避免车厢内物品剧烈晃动、移位、破损。</li>
                <li>行车过程中严禁作业人员在车厢内乘坐、打闹，所有人员必须乘坐驾驶室，严禁超员、超载运输。</li>
                <li>长途运输每2小时停车检查一次车厢物品固定情况，及时加固松动物品，排查行车安全隐患。</li>
            </ol>
            <h4>第二条 停车与装卸安全</h4>
            <ol>
                <li>装卸车辆必须停靠在平整、安全、合规的区域，拉紧手刹、熄火断电，设置警示标识，禁止在陡坡、弯道、消防通道、禁停区域停车作业。</li>
                <li>车辆停靠后确认周边环境安全，方可开启车厢门进行装卸，开门时缓慢操作，防止物品突然滑落砸伤人员。</li>
            </ol>
        </div>
    </details>
    <details class="safety-policy-chapter">
        <summary><h3>第六章 安全隐患排查与事故应急处理</h3></summary>
        <div class="safety-policy-body">
            <h4>第一条 日常隐患排查</h4>
            <ol>
                <li>安全管理员每日开展作业安全巡查，每周组织一次全面安全隐患排查，重点检查人员操作规范、设备工具状态、车辆安全、作业现场防护情况。</li>
                <li>作业中发现安全隐患、违规操作，立即叫停作业，现场整改，整改完成后方可继续施工。</li>
                <li>建立安全隐患台账，记录隐患位置、问题、整改责任人、整改时限及整改结果，实现闭环管理。</li>
            </ol>
            <h4>第二条 事故应急处理流程</h4>
            <ol>
                <li>轻微磕碰、物品小损坏：现场立即停止作业，主动向客户致歉，第一时间上报班组长及公司管理层，协商妥善处理，避免纠纷升级。</li>
                <li>人员轻微受伤：立即停止作业，对伤口进行清洁、包扎处理；伤势较重者，立即送往就近医院救治，同时上报公司负责人。</li>
                <li>交通事故、重大物品损毁、人员重伤事故：第一时间保护现场、抢救伤员，拨打120、122等应急电话，及时上报公司管理层，严禁隐瞒、谎报事故。</li>
                <li>所有事故必须事后复盘，分析事故原因，明确责任，制定整改措施，杜绝同类事故重复发生。</li>
            </ol>
        </div>
    </details>
    <details class="safety-policy-chapter">
        <summary><h3>第七章 安全培训与档案管理</h3></summary>
        <div class="safety-policy-body">
            <h4>第一条 安全培训管理</h4>
            <ol>
                <li>公司每月组织一次全员安全培训，内容涵盖操作规范、交通安全、应急处置、风险防范、案例警示等，留存培训照片、签到表、课件记录。</li>
                <li>新员工必须完成岗前安全培训+实操考核，方可上岗；节假日、旺季作业前开展专项安全交底培训，强化全员安全意识。</li>
            </ol>
            <h4>第二条 安全档案管理</h4>
            <p>建立完善安全管理档案，包含员工安全培训记录、考核成绩、设备检修台账、车辆维保记录、隐患排查整改记录、事故处理记录、安全奖惩记录等，专人负责、定期归档、留存备查。</p>
        </div>
    </details>
    <details class="safety-policy-chapter">
        <summary><h3>第八章 奖惩管理制度</h3></summary>
        <div class="safety-policy-body">
            <h4>第一条 奖励条款</h4>
            <ol>
                <li>严格遵守本制度，全年无违规、无安全事故的员工，给予月度、年度安全表彰及现金奖励。</li>
                <li>及时排查重大安全隐患、规避重大事故发生的员工，给予专项表彰及奖励。</li>
                <li>应急处置得当，妥善化解安全纠纷、降低公司损失的员工，给予相应奖励。</li>
            </ol>
            <h4>第二条 处罚条款</h4>
            <ol>
                <li>作业期间未按规定佩戴防护用品、违规操作、嬉戏打闹、酒后上岗等轻微违规行为，给予口头警告、罚款处理。</li>
                <li>擅自违规操作、野蛮作业，造成客户物品轻微损毁、现场轻微破损的，由责任人承担相应赔偿，并处以罚款。</li>
                <li>车辆违规驾驶、带病出车，引发交通违章或轻微事故的，驾驶员承担全部责任及损失，并处以处罚。</li>
                <li>严重违规作业、拒不服从安全管理，引发重大物品损毁、人员受伤、重大交通事故或严重客户纠纷，给公司造成经济损失和声誉损害的，从严处罚，情节严重者予以辞退，依法追究相关责任。</li>
            </ol>
        </div>
    </details>
    <details class="safety-policy-chapter">
        <summary><h3>第九章 附则</h3></summary>
        <div class="safety-policy-body">
            <p>第一条 本制度由公司管理层负责解释、修订，未尽事宜可根据实际运营情况补充完善。</p>
            <p>第二条 本制度自发布之日起正式执行，全体员工必须严格遵照执行。</p>
            <p>第三条 原有公司安全作业相关规定与本制度不一致的，以本制度为准。</p>
